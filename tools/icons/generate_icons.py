#!/usr/bin/env python3
"""Generates the app's few icons as Android vector drawables, plus an SVG preview sheet.

    python3 tools/icons/generate_icons.py app/src/main/res/drawable tools/icons/build/preview.png

Buttons are words only, like the car's; icons are left only where the car uses symbols (the media
controls) and for the setup guide's pictures. Each icon is a list of parts: (pathData, kind), with
kind "s" for a stroke and "f" for a fill. The app tints the whole icon.
"""
import os
import subprocess
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else "drawable"
SHEET = sys.argv[2] if len(sys.argv) > 2 else "icons.png"
W = 1.7  # stroke width in a 24-unit viewport
COLOR = "#FF000000"


def _ring(cx, cy, r):
    return f"M{cx},{cy} m-{r},0 a{r},{r} 0 1,0 {2*r},0 a{r},{r} 0 1,0 -{2*r},0"


def steering_wheel(cy, r):
    return [
        (_ring(12, cy, r), "s"),
        (f"M{12-r},{cy} L10.6,{cy} M13.4,{cy} L{12+r},{cy} M12,{cy+1.4} L12,{cy+r}", "s"),
        (_ring(12, cy, 1.4), "f"),
    ]


ICONS = {
    # Media controls, as on the car.
    "ic_action_previous": [
        ("M6,5.5 L6,18.5", "s"),
        ("M18.5,6 L8.5,12 L18.5,18 Z", "f"),
    ],
    "ic_action_next": [
        ("M18,5.5 L18,18.5", "s"),
        ("M5.5,6 L15.5,12 L5.5,18 Z", "f"),
    ],
    "ic_action_play_pause": [
        ("M3,5.5 L12,12 L3,18.5 Z", "f"),
        ("M15.5,6 L15.5,18 M20.5,6 L20.5,18", "s"),
    ],
    # The setup guide's key roles.
    "ic_action_role_driver": steering_wheel(12, 8.5),
    "ic_action_role_owner": [
        ("M10,7.5 m-3.5,0 a3.5,3.5 0 1,0 7,0 a3.5,3.5 0 1,0 -7,0", "s"),
        ("M3.5,20 Q3.5,13.5 10,13.5 Q11.5,13.5 12.6,13.9", "s"),
        ("M17,15.5 m-2.2,0 a2.2,2.2 0 1,0 4.4,0 a2.2,2.2 0 1,0 -4.4,0", "s"),
        ("M17,17.7 L17,21.5 M17,19.6 L18.6,19.6 M17,21.2 L18.2,21.2", "s"),
    ],
}


def vector_xml(parts):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by tools/icons/generate_icons.py; edit that instead. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        '    android:viewportWidth="24"',
        '    android:viewportHeight="24">',
    ]
    for d, kind in parts:
        if kind == "s":
            attrs = [f'android:pathData="{d}"', f'android:strokeColor="{COLOR}"', f'android:strokeWidth="{W}"',
                     'android:strokeLineCap="round"', 'android:strokeLineJoin="round"']
        else:
            attrs = [f'android:pathData="{d}"', f'android:fillColor="{COLOR}"']
        lines.append("    <path\n        " + "\n        ".join(attrs) + " />")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def svg_sheet(icons, cols=6, cell=120):
    rows = (len(icons) + cols - 1) // cols
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{cols*cell}" height="{rows*(cell+24)}">',
           '<rect width="100%" height="100%" fill="#26282B"/>']
    for i, (name, parts) in enumerate(icons.items()):
        x0, y0 = (i % cols) * cell, (i // cols) * (cell + 24)
        out.append(f'<g transform="translate({x0+10},{y0+8}) scale({100 / 24:.3f})">')
        for d, kind in parts:
            if kind == "s":
                out.append(f'<path d="{d}" fill="none" stroke="#ECEDEE" stroke-width="{W}" stroke-linecap="round" stroke-linejoin="round"/>')
            else:
                out.append(f'<path d="{d}" fill="#ECEDEE"/>')
        out.append("</g>")
        out.append(f'<text x="{x0+6}" y="{y0+cell+14}" font-size="12" fill="#B5B8BD" font-family="sans-serif">{name.replace("ic_action_", "")}</text>')
    out.append("</svg>")
    return "\n".join(out)


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(os.path.dirname(SHEET) or ".", exist_ok=True)
    for name, parts in ICONS.items():
        with open(os.path.join(OUT, name + ".xml"), "w") as f:
            f.write(vector_xml(parts))
    svg = os.path.splitext(SHEET)[0] + ".svg"
    with open(svg, "w") as f:
        f.write(svg_sheet(ICONS))
    # ImageMagick renders the preview; the drawables don't need it.
    if subprocess.run(["magick", svg, SHEET]).returncode != 0:
        print("no preview: ImageMagick missing")
    print(f"{len(ICONS)} icons -> {OUT}, preview {SHEET}")
