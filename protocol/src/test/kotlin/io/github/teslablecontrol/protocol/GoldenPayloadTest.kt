package io.github.teslablecontrol.protocol

import com.tesla.generated.carserver.server.CarServer
import com.tesla.generated.vcsec.Vcsec
import io.github.teslablecontrol.protocol.commands.CommandCatalog
import io.github.teslablecontrol.protocol.vehicle.VehicleRequest
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import kotlin.test.fail

/**
 * Every command payload must equal what the official Go client sends for the same arguments.
 * `golden/commands.json` is generated by `tools/vehicle-sim/build.sh --golden`, which drives
 * vehicle-command's `pkg/vehicle` against the reference simulator and records what it received.
 */
class GoldenPayloadTest {
    private class Case(val id: String, val args: Map<String, String>, val kind: String, val payload: ByteArray)

    private val cases: List<Case> by lazy {
        val text = javaClass.getResource("/golden/commands.json")?.readText() ?: fail("golden/commands.json missing")
        Json.parseToJsonElement(text).jsonArray.map { element ->
            val o = element.jsonObject
            Case(
                id = o.getValue("id").jsonPrimitive.content,
                args = o.getValue("args").jsonObject.mapValues { it.value.jsonPrimitive.content },
                kind = o.getValue("kind").jsonPrimitive.content,
                payload = o.getValue("payload").jsonPrimitive.content.hexToBytes(),
            )
        }
    }

    @Test
    fun goldenFileCoversEveryCommand() {
        assertEquals(CommandCatalog.all.map { it.id }.toSet(), cases.map { it.id }.toSet())
    }

    @Test
    fun payloadsMatchOfficialClient() {
        val mismatches = mutableListOf<String>()
        for (case in cases) {
            val request = CommandCatalog[case.id].build(case.args) { 1_700_000_000 }
            val expectedKind = when (request) {
                is VehicleRequest.CarServerAction, is VehicleRequest.State -> "carserver"
                is VehicleRequest.AddKeyRequest -> "raw"
                is VehicleRequest.SessionInfoQuery -> "sessioninfo"
                else -> "vcsec"
            }
            if (case.kind != expectedKind) {
                mismatches += "${case.id} ${case.args}: sent to ${case.kind}, we target $expectedKind"
                continue
            }
            // Compare decoded messages: protobuf allows fields in any order, and Go orders oneof
            // fields differently from Java, so byte equality is not required by the vehicle.
            val ours = decode(case.kind, request.payload())
            val theirs = decode(case.kind, case.payload)
            if (ours != theirs) {
                mismatches += "${case.id} ${case.args}:\n  ours   = $ours\n  theirs = $theirs"
            }
        }
        assertTrue(mismatches.isEmpty(), mismatches.joinToString("\n"))
    }

    private fun decode(kind: String, bytes: ByteArray): Any = when (kind) {
        "carserver" -> CarServer.Action.parseFrom(bytes)
        "vcsec" -> Vcsec.UnsignedMessage.parseFrom(bytes)
        "raw" -> Vcsec.ToVCSECMessage.parseFrom(bytes).let { envelope ->
            // Compare the nested payload decoded, for the same field-order reason.
            val signed = envelope.signedMessage
            val inner = Vcsec.UnsignedMessage.parseFrom(signed.protobufMessageAsBytes)
            envelope.toBuilder().setSignedMessage(signed.toBuilder().clearProtobufMessageAsBytes()).build() to inner
        }
        "sessioninfo" -> bytes.toHex()
        else -> fail("unknown kind $kind")
    }
}
